import { expect, test } from '@playwright/test';
import path from 'node:path';

const qaDir=path.resolve(process.cwd(),'../validation/phase7');
function watchConsole(page:import('@playwright/test').Page){
  const errors:string[]=[];
  page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
  page.on('pageerror',error=>errors.push(error.message));
  return errors;
}

test('desktop English journey covers methods, boundaries, comparisons, rankings and keyboard use',async({page},testInfo)=>{
  test.skip(testInfo.project.name!=='desktop','desktop journey');
  const errors=watchConsole(page);
  await page.goto('/');
  await expect(page.locator('#hero-median')).not.toHaveText('—',{timeout:30_000});
  await expect(page.locator('.language-header')).toBeVisible();
  await expect(page.locator('.language-sticky')).toBeHidden();
  await expect(page.locator('#coverage-chart svg')).toBeVisible();
  await expect(page.locator('.median-line,.median-label')).toHaveCount(0);
  await expect(page.locator('#coverage-chart .chart-legend')).toBeVisible();
  const chartBox=await page.locator('#coverage-chart > svg').boundingBox(),legendBox=await page.locator('#coverage-chart .chart-legend').boundingBox();
  expect(legendBox!.y).toBeGreaterThan(chartBox!.y+chartBox!.height-2);
  await page.locator('#coverage-chart .chart-overlay').hover({position:{x:240,y:120}});
  await expect(page.locator('#coverage-chart .chart-focus')).toHaveAttribute('visibility','visible');
  await expect(page.locator('#coverage-chart .focus-dot')).toHaveCount(1);
  await expect(page.locator('#tooltip .tooltip-row')).toHaveCount(1);
  await expect(page.locator('#tooltip .tooltip-series')).toHaveCSS('border-top-style','solid');
  await expect(page.locator('#residential-map canvas')).toBeVisible();
  await page.locator('#residential-map').scrollIntoViewIfNeeded();
  await expect(page.locator('.language-sticky')).toBeVisible();
  await page.evaluate(()=>(window as Window & {__railMaps:{residential:{resize:()=>void}}}).__railMaps.residential.resize());
  await expect.poll(()=>page.evaluate(()=>(window as Window & {__railMaps:{residential:{queryRenderedFeatures:(options:unknown)=>unknown[]}}}).__railMaps.residential.queryRenderedFeatures({layers:['residential-components']}).length),{message:'building-detail PMTiles render at the default zoom',timeout:20_000}).toBeGreaterThan(0);
  await expect.poll(()=>page.evaluate(()=>(window as Window & {__railMaps:{residential:{getZoom:()=>number}}}).__railMaps.residential.getZoom()),{message:'residential map starts at building-detail zoom'}).toBeGreaterThanOrEqual(11);
  expect(await page.evaluate(()=>(window as Window & {__railMaps:{residential:{getLayer:(id:string)=>unknown}}}).__railMaps.residential.getLayer('distance-surface'))).toBeFalsy();
  await expect(page.locator('.station-anchor').first()).toHaveCSS('width','14px');
  await page.locator('[data-coverage-method="platform"]').click();
  await expect(page.locator('[data-coverage-method="platform"]')).toHaveAttribute('aria-pressed','true');
  await page.locator('[data-coverage-method="compare"]').click();
  await page.locator('[data-rail-view="nested"]').click();
  await expect(page.locator('#coverage-chart .focus-dot')).toHaveCount(6);
  await expect(page.locator('#distribution-chart .chart-line')).toHaveCount(6);
  await page.locator('[data-geography="city"]').click();
  await expect(page.locator('[data-geography="city"]')).toHaveAttribute('aria-pressed','true');
  await page.locator('#district-2').selectOption('district_02');
  await page.locator('#district-3').selectOption('district_03');
  await expect(page.locator('#district-chart .chart-line')).toHaveCount(3);
  await page.locator('[data-map-method="platform"]').click();
  await page.locator('#map-reset').focus();
  await page.keyboard.press('Enter');
  const sol=await page.evaluate(async()=>{
    const payload=await fetch('data/phase7.json').then(r=>r.json());
    const station=payload.stations.find((candidate:{station_name:string})=>candidate.station_name==='Sol');
    const map=(window as Window & {__railMaps:{residential:{jumpTo:(options:unknown)=>void;project:(coordinates:number[])=>{x:number;y:number}}}}).__railMaps.residential;
    map.jumpTo({center:[station.longitude,station.latitude],zoom:14});
    const point=map.project([station.longitude,station.latitude]);
    return {id:station.station_id,x:point.x,y:point.y};
  });
  const solMarker=page.locator(`.station-anchor[data-station-id="${sol.id}"]`);
  await expect(solMarker).toBeVisible();
  await expect.poll(()=>page.evaluate(()=>(window as Window & {__railMaps:{residential:{queryRenderedFeatures:(options:unknown)=>unknown[]}}}).__railMaps.residential.queryRenderedFeatures({layers:['origin-points']}).length),{message:'origins appear automatically at close zoom',timeout:20_000}).toBeGreaterThan(0);
  await solMarker.click();
  await expect(page.locator('#station-card h3')).toHaveText('Sol');
  await expect.poll(()=>page.evaluate(()=>(window as Window & {__railMaps:{residential:{queryRenderedFeatures:(options:unknown)=>unknown[]}}}).__railMaps.residential.queryRenderedFeatures({layers:['residential-components']}).length),{message:'detailed component PMTiles rendered at close zoom',timeout:20_000}).toBeGreaterThan(0);
  await expect.poll(()=>page.evaluate(()=>(window as Window & {__railMaps:{residential:{queryRenderedFeatures:(options:unknown)=>unknown[]}}}).__railMaps.residential.queryRenderedFeatures({layers:['origin-points']}).length),{message:'selected platform origins rendered',timeout:20_000}).toBeGreaterThan(0);
  await expect(page.locator('.station-name-popup')).toBeVisible();
  await solMarker.click();
  await expect(page.locator('.station-name-popup')).toHaveCount(0);
  await expect.poll(()=>page.evaluate(()=>(window as Window & {__railMaps:{residential:{queryRenderedFeatures:(options:unknown)=>unknown[]}}}).__railMaps.residential.queryRenderedFeatures({layers:['origin-points']}).length),{message:'station origins close when station is toggled off',timeout:10_000}).toBe(0);
  await solMarker.click();
  await page.locator('#station-2').fill('Sol');
  await page.locator('#station-2').press('Tab');
  await page.locator('#ranking-metric').selectOption('hinterland');
  await expect(page.locator('#radius-label')).toBeHidden();
  const firstBar=page.locator('#ranking-chart rect[role="button"]').first();
  await firstBar.focus();
  await page.keyboard.press('Enter');
  await expect(page.locator('#station-card h3')).not.toHaveText('');
  await expect(page.locator('.station-value-marker.selected')).toHaveCount(1);
  await expect.poll(()=>page.evaluate(()=>(window as Window & {__railMaps:{station:{getZoom:()=>number}}}).__railMaps.station.getZoom()),{message:'ranking selection zooms the station map closer'}).toBeGreaterThanOrEqual(13);
  await expect(page.locator('#stations .axis text').first()).toHaveCSS('fill','rgb(255, 255, 255)');
  await expect(page.locator('#station-card .mode-marks img').first()).toBeVisible();
  await expect(page.locator('footer [data-i18n="sources"]')).toHaveText('Sources:');
  await page.waitForTimeout(2000);
  await page.evaluate(()=>{(document.activeElement as HTMLElement|null)?.blur();});
  await page.locator('#stations').screenshot({path:path.join(qaDir,'desktop-stations.png')});
  expect(errors,'browser console errors').toEqual([]);
});

test('390 px Spanish journey and reduced motion remain complete',async({page},testInfo)=>{
  test.skip(testInfo.project.name!=='mobile','mobile journey');
  const errors=watchConsole(page);
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.goto('/?lang=es');
  await expect(page.locator('h1')).toContainText('distancia',{timeout:30_000});
  await expect(page.locator('[data-i18n="distanceTag"]').first()).toHaveText('Distancia en línea recta');
  await expect(page.locator('[data-i18n="resetExtent"]')).toHaveText('Reiniciar mapa');
  await expect(page.locator('[data-i18n="neighbourBody"]')).toContainText('¿Cómo de bien cubre el tren');
  await expect(page.locator('[data-i18n="methodsTitle"]')).toContainText('limitaciones explícitas');
  await expect(page.locator('footer [data-i18n="sources"]')).toHaveText('Fuentes:');
  await page.locator('[data-coverage-method="platform"]').click();
  await page.locator('[data-geography="city"]').click();
  await page.locator('#district-2').selectOption('district_02');
  await page.locator('#district-3').selectOption('district_03');
  await expect(page.locator('#coverage-chart svg')).toBeVisible();
  await expect(page.locator('#station-map canvas')).toBeVisible();
  await page.waitForTimeout(2000);
  await page.evaluate(()=>{(document.activeElement as HTMLElement|null)?.blur();});
  await page.locator('#coverage').screenshot({path:path.join(qaDir,'mobile-coverage-es.png')});
  expect(errors,'browser console errors').toEqual([]);
});
